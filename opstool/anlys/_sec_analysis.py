class MomentCurvature:
    """Moment-curvature analysis and approximate N-My-Mz interaction for fiber sections.

    The section materials and fiber section must be defined in OpenSeesPy before
    creating or running this object.  The analysis model is a two-node
    ``zeroLengthSection`` element with axial load applied first and held
    constant, followed by displacement-control curvature loading about the
    requested bending axis.

    Sign conventions follow OpenSeesPy:

    - ``axial_force < 0`` means compression.
    - ``axis="y"`` controls rotational DOF 5 and returns the load factor of a
      unit moment about the local y-axis.
    - ``axis="z"`` controls rotational DOF 6 and returns the load factor of a
      unit moment about the local z-axis.
    - Fiber data columns are ``yloc, zloc, area, mat, stress, strain``.

    Parameters
    ----------
    sec_tag : int
        Tag of a previously defined fiber section.
    axial_force : float, optional
        Constant axial load. Compression is negative.

    Attributes
    ----------
    phi : numpy.ndarray or None
        Curvature history after :meth:`analyze`.
    M : numpy.ndarray or None
        Moment history after :meth:`analyze`.
    FiberData : numpy.ndarray or None
        Fiber response history with shape ``(n_step, n_fiber, 6)``.
    cycle_path : numpy.ndarray or None
        Target curvature path used when ``cycle_analyze=True``.
    NMMresult : dict
        Result dictionary generated by :meth:`build_NMM`.

    Examples
    --------
    >>> mc = MomentCurvature(sec_tag=1, axial_force=-500e3)
    >>> mc.analyze(axis="y", max_phi=0.05, incr_phi=1e-4)
    >>> phi, moment = mc.get_M_phi()
    >>> phi_u, moment_u = mc.get_limit_state(matTag=1, threshold=-0.003)
    """

    def __init__(self, sec_tag: int, axial_force: float = 0) -> None:
        self.P = float(axial_force)
        self.sec_tag = int(sec_tag)
        self.phi: np.ndarray | None = None
        self.M: np.ndarray | None = None
        self.FiberData: np.ndarray | None = None
        self.cycle_path: np.ndarray | None = None
        self.NMMresult: dict[str, np.ndarray | str] = {}

    def new(self, sec_tag: int, axial_force: float = 0) -> MomentCurvature:
        """Reset the object for another section or axial load.

        This clears all stored analysis results, cyclic path data and NMM
        results, then returns ``self`` so calls can be chained.

        Parameters
        ----------
        sec_tag : int
            Tag of a previously defined fiber section.
        axial_force : float, optional
            Constant axial load. Compression is negative.

        Returns
        -------
        MomentCurvature
            The same object after reinitialization.
        """
        self.P = float(axial_force)
        self.sec_tag = int(sec_tag)
        self.phi = None
        self.M = None
        self.FiberData = None
        self.cycle_path = None
        self.NMMresult = {}
        return self

    def analyze(
        self,
        axis: Axis = "y",
        max_phi: float = 0.05,
        incr_phi: float = 1e-4,
        limit_peak_ratio: float = 0.8,
        cycle_analyze: bool = False,
        smart_analyze: bool = True,
        debug: bool = False,
    ) -> None:
        """Run the moment-curvature analysis.

        Results are stored in ``phi``, ``M`` and ``FiberData``.  The analysis
        terminates when the requested curvature is reached, or when the
        post-peak moment has dropped below ``limit_peak_ratio`` with unloading
        slope reversal.

        Parameters
        ----------
        axis : {"y", "z"}, optional
            Bending axis. ``"y"`` controls DOF 5; ``"z"`` controls DOF 6.
        max_phi : float, optional
            Target maximum curvature. The sign sets the monotonic loading
            direction. For cyclic analysis, this is replaced by the maximum
            absolute value in ``cycle_path``.
        incr_phi : float, optional
            Nominal curvature increment used to discretize the loading path.
        limit_peak_ratio : float, optional
            Stop ratio after peak moment. For example, ``0.8`` stops after a
            20 percent strength drop once the response is descending.
        cycle_analyze : bool, optional
            If ``True``, use the path created by :meth:`set_cycle_path`.
        smart_analyze : bool, optional
            If ``True``, use :class:`SmartAnalyze` to retry failed steps with
            alternate algorithms and step relaxation.
        debug : bool, optional
            If ``True``, print OpenSees convergence details.

        Notes
        -----
        Existing OpenSees nodes/elements are reused when present.  Analysis
        patterns and time series with tags 1 and 2 are removed before the new
        run, so avoid using those tags for unrelated loads during this helper.
        """
        self.phi, self.M, self.FiberData = _analyze(
            sec_tag=self.sec_tag,
            P=self.P,
            axis=axis,
            max_phi=max_phi,
            incr_phi=incr_phi,
            stop_ratio=limit_peak_ratio,
            cycle=cycle_analyze,
            cycle_path=self.cycle_path,
            smart_analyze=smart_analyze,
            need_resp=True,
            debug=debug,
        )
        print("MomentCurvature: analysis complete.")

    def set_cycle_path(self, max_phi: float, n_cycle: int = 20, n_hold: int = 1) -> np.ndarray:
        """Build a symmetric incrementally growing cyclic curvature path.

        The generated path starts at zero, alternates positive and negative
        target curvatures with increasing amplitude, and returns to zero.  It
        is stored in ``cycle_path`` and used by :meth:`analyze` when
        ``cycle_analyze=True``.

        Parameters
        ----------
        max_phi : float
            Peak absolute curvature. The sign is ignored.
        n_cycle : int, optional
            Number of amplitude levels including zero. Must be at least 2.
        n_hold : int, optional
            Number of repetitions for each positive/negative amplitude pair.

        Returns
        -------
        numpy.ndarray
            Curvature target sequence, including the initial and final zero.
        """
        if n_cycle < 2:
            raise ValueError("n_cycle must be >= 2.")  # noqa: TRY003
        if n_hold < 1:
            raise ValueError("n_hold must be >= 1.")  # noqa: TRY003

        max_phi = abs(float(max_phi))
        upper = np.linspace(0.0, max_phi, int(n_cycle))[1:]
        below = np.linspace(0.0, -max_phi, int(n_cycle))[1:]
        pattern = [0.0]
        for up, low in zip(upper, below):
            for _ in range(int(n_hold)):
                pattern.extend([float(up), float(low)])
        pattern.append(0.0)
        self.cycle_path = np.asarray(pattern, dtype=float)
        return self.cycle_path.copy()

    setCyclePath = set_cycle_path

    def plot_M_phi(self, ax=None):
        """Plot the moment-curvature relationship.

        Parameters
        ----------
        ax : matplotlib.axes.Axes, optional
            Axes to draw on. A new figure and axes are created when omitted.

        Returns
        -------
        matplotlib.axes.Axes
            Axes containing the plot.
        """
        self._require_result()
        lw = 0.8 if self.cycle_path is not None else 1.5
        if ax is None:
            _, ax = plt.subplots(1, 1, figsize=(8, 5))
        ax.plot(self.phi, self.M, lw=lw, c="blue")
        ax.set_title("$M-\\phi$", fontsize=18)
        ax.set_xlabel("$\\phi$", fontsize=14)
        ax.set_ylabel("$M$", fontsize=14)
        ax.grid(True)
        return ax

    plotMPhi = plot_M_phi

    def plot_fiber_responses(
        self,
        matTag: int | list[int] | np.ndarray | None = None,
        line_width: float = 0.7,
        max_fibers: int | float = np.inf,
        sharex: bool = False,
        sharey: bool = False,
        return_ax: bool = False,
    ):
        """Plot fiber stress-strain histories.

        Parameters
        ----------
        matTag : int or array-like, optional
            Material tag or tags to plot. When omitted, all material tags found
            in the final fiber state are plotted.
        line_width : float, optional
            Width of each stress-strain curve.
        max_fibers : int or float, optional
            Maximum number of fibers plotted per material tag. Large fiber
            groups are uniformly subsampled for readability.
        sharex, sharey : bool, optional
            Share subplot x or y limits.
        return_ax : bool, optional
            If ``True``, return the axes array. Otherwise return ``None``.

        Returns
        -------
        numpy.ndarray or None
            Matplotlib axes when ``return_ax=True``.
        """
        self._require_result()
        fiber_data = self.FiberData
        tags = np.unique(fiber_data[-1, :, 3]) if matTag is None else np.atleast_1d(matTag).astype(float)
        _, axs = plt.subplots(len(tags), 1, figsize=(8, 3 * len(tags)), squeeze=False, sharex=sharex, sharey=sharey)
        axs = axs.ravel()

        for tag, ax in zip(tags, axs):
            idxs = np.flatnonzero(np.abs(fiber_data[-1, :, 3] - tag) < 1e-6)
            if idxs.size == 0:
                warn(f"matTag {tag:g} not found; skipped.", stacklevel=2)
                continue
            if np.isfinite(max_fibers) and idxs.size > int(max_fibers):
                keep = np.linspace(0, idxs.size - 1, int(max_fibers), dtype=int)
                idxs = idxs[keep]
            ax.plot(fiber_data[:, idxs, 5], fiber_data[:, idxs, 4], lw=line_width)
            ax.set_title(f"matTag = {tag:g}, nFiber = {idxs.size}", fontsize=13)
            ax.set_xlabel("Strain", fontsize=12)
            ax.set_ylabel("Stress", fontsize=12)
            ax.grid(True)
        plt.tight_layout()
        if return_ax:
            return axs
        return None

