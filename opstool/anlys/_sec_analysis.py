    def get_limit_state(
        self,
        matTag: int | list[int] | np.ndarray = 1,
        threshold: float | list[float] | np.ndarray = 0.0,
        peak_drop: float | bool = False,
        return_index: bool = False,
    ):
        """Return curvature and moment at a limit state.

        Two limit-state modes are supported:

        - Strain-threshold mode, used when ``peak_drop=False``.  The first
          step is selected where any fiber of the requested material reaches
          its strain threshold.
        - Peak-drop mode, used when ``peak_drop`` is ``True`` or a float.  The
          first post-peak step is selected where ``abs(M)`` has dropped by the
          requested fraction.

        Parameters
        ----------
        matTag : int or array-like, optional
            Material tag or tags monitored in strain-threshold mode.
        threshold : float or array-like, optional
            Strain threshold for each material tag. A positive value monitors
            tensile strain with ``max(strain) >= threshold``. A negative value
            monitors compressive strain with ``min(strain) <= threshold``. A
            scalar threshold is broadcast to multiple material tags.
        peak_drop : bool or float, optional
            If ``False``, use strain-threshold mode. If ``True``, use a default
            20 percent post-peak drop. If a float, it must be the drop fraction
            in ``(0, 1)``; for example ``0.3`` means a 30 percent drop from
            peak strength.
        return_index : bool, optional
            If ``True``, also return the zero-based result index.

        Returns
        -------
        tuple
            ``(phi_u, M_u)`` or ``(phi_u, M_u, index)``.
        """
        self._require_result()
        if peak_drop is not False:
            drop = 0.20 if peak_drop is True else float(peak_drop)
            moment, idx = _extract_moment_capacity(
                self.phi,
                self.M,
                self.FiberData,
                cap_mode="peakdrop",
                peak_drop=drop,
                mat_tag=matTag,
                threshold=threshold,
            )
        else:
            moment, idx = _extract_moment_capacity(
                self.phi,
                self.M,
                self.FiberData,
                cap_mode="strain",
                mat_tag=matTag,
                threshold=threshold,
            )
        result = (float(self.phi[idx]), float(moment))
        if return_index:
            return (*result, int(idx))
        return result

    getLimitState = get_limit_state

    def bilinearize(self, phiy: float, My: float, phiu: float, plot: bool = False, ax=None):
        """Compute an equal-area bilinear approximation.

        The initial elastic stiffness ``k = My / phiy`` is preserved.  The
        equivalent yield point is chosen so the bilinear curve has the same
        area as the actual moment-curvature curve up to ``phiu``.  Positive
        and negative loading branches are both supported.

        Parameters
        ----------
        phiy : float
            Initial yield curvature. Must be nonzero.
        My : float
            Initial yield moment. Must be nonzero.
        phiu : float
            Ultimate or target curvature used as the integration end point.
            The sign selects the loading branch.
        plot : bool, optional
            If ``True``, draw the original branch and bilinear curve.
        ax : matplotlib.axes.Axes, optional
            Axes used when ``plot=True``.

        Returns
        -------
        tuple[float, float]
            Equivalent yield curvature and moment ``(phi_eq, M_eq)``.
        """
        self._require_result()
        phi_eq, m_eq, idx_u = _bilinearize(self.phi, self.M, phiy, My, phiu)

        if plot:
            ax = _plot_bilinear(self.phi, self.M, phiy, My, phiu, phi_eq, m_eq, idx_u, ax=ax)
            # return phi_eq, m_eq, idx_u, ax
        return phi_eq, m_eq

    def build_NMM(
        self,
        NList: np.ndarray | list[float] | None = None,
        axis1: Axis = "y",
        axis2: Axis = "z",
        phiMax: float = 0.05,
        incrPhi: float = 1e-4,
        nTheta: int = 36,
        limitPeakRatio: float = 0.8,
        smartAnalyze: bool = True,
        useParallel: bool = False,
        capacityMode: CapacityMode = "peak",
        peakDrop: float = 0.20,
        matTag: int | list[int] | np.ndarray = 1,
        threshold: float | list[float] | np.ndarray = 0.0,
        targetPhi: float | None = None,
        MyCapManual: np.ndarray | list[float] | None = None,
        MzCapManual: np.ndarray | list[float] | None = None,
        debug: bool = False,
    ) -> dict[str, np.ndarray | str]:
        """Build an approximate N-My-Mz interaction surface.

        For each axial load, capacities about ``axis1`` and ``axis2`` are
        obtained from uniaxial moment-curvature analyses.  The biaxial contour
        is then generated from the ellipse equation
        ``(My/MyCap)^2 + (Mz/MzCap)^2 = 1``.

        Parameters
        ----------
        NList : array-like, optional
            Axial load levels. Compression should be negative.
        axis1, axis2 : {"y", "z"}, optional
            Bending axes used to obtain the two uniaxial capacities.
        phiMax : float, optional
            Maximum curvature for each uniaxial analysis.
        incrPhi : float, optional
            Curvature increment for each uniaxial analysis.
        nTheta : int, optional
            Number of angular divisions around each My-Mz contour. The stored
            contour is closed, so ``My`` and ``Mz`` have ``nTheta + 1`` columns.
        limitPeakRatio : float, optional
            Stop ratio passed to each uniaxial analysis.
        smartAnalyze : bool, optional
            Use :class:`SmartAnalyze` during the uniaxial analyses.
        useParallel : bool, optional
            Accepted for MATLAB API compatibility. OpenSeesPy uses one global
            interpreter, so this implementation runs sequentially.
        capacityMode : {"peak", "peakdrop", "strain", "curvature", "manual"}, optional
            Rule used to extract each uniaxial capacity.
        peakDrop : float, optional
            Drop fraction for ``capacityMode="peakdrop"``.
        matTag, threshold : int or array-like, optional
            Material tags and strain thresholds for ``capacityMode="strain"``.
        targetPhi : float, optional
            Curvature used for ``capacityMode="curvature"``.
        MyCapManual, MzCapManual : array-like, optional
            User-supplied capacities for ``capacityMode="manual"``. Each must
            have the same length as ``NList``.
        debug : bool, optional
            Print convergence details during uniaxial analyses.

        Returns
        -------
        dict
            Result dictionary stored in ``NMMresult`` with keys ``N``, ``My``,
            ``Mz``, ``thetas``, ``MyCap``, ``MzCap`` and ``capMode``.

        Notes
        -----
        The NMM surface is an engineering approximation based on elliptical
        interpolation between two uniaxial capacities at each axial load.  It
        is not a full biaxial nonlinear section analysis.
        """
        if NList is None:
            NList = np.linspace(-1e6, 0.0, 8)
        n_list = np.asarray(NList, dtype=float).reshape(-1)
        if n_list.size == 0:
            raise ValueError("NList must not be empty.")  # noqa: TRY003
        if int(nTheta) < 4:
            raise ValueError("nTheta must be >= 4.")  # noqa: TRY003
        if useParallel:
            warn(
                "useParallel=True is accepted for MATLAB API compatibility but is not used by OpenSeesPy.", stacklevel=2
            )

        cap_mode = _normalize_capacity_mode(capacityMode)
        if cap_mode == "manual":
            if MyCapManual is None or MzCapManual is None:
                raise ValueError("MyCapManual and MzCapManual are required when capacityMode='manual'.")  # noqa: TRY003
            my_cap = np.abs(np.asarray(MyCapManual, dtype=float).reshape(-1))
            mz_cap = np.abs(np.asarray(MzCapManual, dtype=float).reshape(-1))
            if my_cap.size != n_list.size or mz_cap.size != n_list.size:
                raise ValueError("MyCapManual and MzCapManual must match the length of NList.")  # noqa: TRY003
        else:
            need_resp = cap_mode == "strain"
            my_cap = np.zeros(n_list.size, dtype=float)
            mz_cap = np.zeros(n_list.size, dtype=float)
            print(f"build_NMM: capacityMode={cap_mode}, {n_list.size} levels x 2 analyses.")
            for i, n_val in enumerate(n_list):
                print(f"  N = {n_val:+.3e} ({i + 1}/{n_list.size})")
                p1, m1, f1 = _analyze(
                    self.sec_tag,
                    P=n_val,
                    axis=axis1,
                    max_phi=phiMax,
                    incr_phi=incrPhi,
                    stop_ratio=limitPeakRatio,
                    smart_analyze=smartAnalyze,
                    need_resp=need_resp,
                    debug=debug,
                )
                p2, m2, f2 = _analyze(
                    self.sec_tag,
                    P=n_val,
                    axis=axis2,
                    max_phi=phiMax,
                    incr_phi=incrPhi,
                    stop_ratio=limitPeakRatio,
                    smart_analyze=smartAnalyze,
                    need_resp=need_resp,
                    debug=debug,
                )
                my_cap[i] = abs(
                    _extract_moment_capacity(p1, m1, f1, cap_mode, peakDrop, matTag, threshold, targetPhi)[0]
                )
                mz_cap[i] = abs(
                    _extract_moment_capacity(p2, m2, f2, cap_mode, peakDrop, matTag, threshold, targetPhi)[0]
                )

        if np.any(~np.isfinite(my_cap)) or np.any(my_cap <= 0) or np.any(~np.isfinite(mz_cap)) or np.any(mz_cap <= 0):
            raise ValueError("All MyCap and MzCap entries must be positive and finite.")  # noqa: TRY003

        thetas = np.linspace(0.0, 2.0 * np.pi, int(nTheta), endpoint=False)
        cos_t = np.cos(thetas)[None, :]
        sin_t = np.sin(thetas)[None, :]
        denom = (cos_t / my_cap[:, None]) ** 2 + (sin_t / mz_cap[:, None]) ** 2
        radius = 1.0 / np.sqrt(denom)
        my_grid = radius * cos_t
        mz_grid = radius * sin_t

        my_grid = np.column_stack((my_grid, my_grid[:, 0]))
        mz_grid = np.column_stack((mz_grid, mz_grid[:, 0]))
        theta_closed = np.r_[thetas, thetas[0] + 2.0 * np.pi]

        self.NMMresult = {
            "N": n_list,
            "My": my_grid,
            "Mz": mz_grid,
            "thetas": theta_closed,
            "MyCap": my_cap,
            "MzCap": mz_cap,
            "MyPeak": my_cap,
            "MzPeak": mz_cap,
            "capMode": cap_mode,
        }
        print(f"build_NMM: done. ({0 if cap_mode == 'manual' else n_list.size * 2} OpenSees analyses)")
        return self.NMMresult

    build_nmm = build_NMM
    buildNMM = build_NMM

    def plot_NMM(
        self,
        normalize: bool = False,
        alpha: float = 0.5,
        colormap: str = "turbo",
        showSurface: bool = True,
        showPlanView: bool = True,
        showEnvelope: bool = True,
    ) -> dict[str, object]:
        """Plot N-My-Mz interaction results generated by :meth:`build_NMM`.

        Parameters
        ----------
        normalize : bool, optional
            Normalize plotted axes by their maximum absolute values.
        alpha : float, optional
            Transparency of the 3D surface.
        colormap : str, optional
            Matplotlib colormap name.
        showSurface, showPlanView, showEnvelope : bool, optional
            Toggle the 3D surface, My-Mz plan contours and uniaxial N-M
            capacity envelope figures.

        Returns
        -------
        dict
            Dictionary with keys ``surface``, ``plan`` and ``envelope``. Values
            are Matplotlib axes, or ``None`` for views that were not requested.
        """
        if not self.NMMresult:
            raise RuntimeError("Run build_NMM() before plot_NMM().")  # noqa: TRY003

        res = self.NMMresult
        n = np.asarray(res["N"], dtype=float)
        my = np.asarray(res["My"], dtype=float)
        mz = np.asarray(res["Mz"], dtype=float)
        my_cap = np.asarray(res["MyCap"], dtype=float)
        mz_cap = np.asarray(res["MzCap"], dtype=float)
        z = np.repeat(n[:, None], my.shape[1], axis=1)
        x_label, y_label, z_label = "$M_y$", "$M_z$", "$N$"

        if normalize:
            sx = _safe_scale(my)
            sy = _safe_scale(mz)
            sz = _safe_scale(n)
            my = my / sx
            mz = mz / sy
            z = z / sz
            my_cap = my_cap / sx
            mz_cap = mz_cap / sy
            n = n / sz
            x_label, y_label, z_label = "$M_y/max|M_y|$", "$M_z/max|M_z|$", "$N/max|N|$"

        cap_mode = str(res.get("capMode", "peak"))
        cmap = plt.get_cmap(colormap)
        colors = cmap(np.linspace(0.0, 1.0, len(n)))
        axs = {"surface": None, "plan": None, "envelope": None}

        if showSurface:
            fig = plt.figure(figsize=(9.2, 7.0))
            ax = fig.add_subplot(111, projection="3d")
            axs["surface"] = ax
            ax.plot_surface(my, mz, z, alpha=alpha, edgecolor="none", cmap=colormap)
            for i, color in enumerate(colors):
                ax.plot(my[i], mz[i], z[i], color=color, lw=1.2)
            step = max(1, my.shape[1] // 12)
            for j in range(0, my.shape[1], step):
                ax.plot(my[:, j], mz[:, j], z[:, j], color=(0, 0, 0, 0.22), lw=0.4)
            ax.set_xlabel(x_label)
            ax.set_ylabel(y_label)
            ax.set_zlabel(z_label)
            ax.set_title(f"N-My-Mz Interaction Surface [{cap_mode}]")
